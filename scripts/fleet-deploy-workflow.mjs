// Fleet regeneration of game deploy workflows (#488, #438).
//
// Rewrites `.github/workflows/deploy.yml` in freegamestore-online game repos to
// GAME_DEPLOY_WORKFLOW from packages/compliance (build it first), the keyless
// caller of ci-workflows game-deploy.yml, and bumps `@freegamestore/games` to
// GAMES_SDK (#498) with a lockfile-only resolve. Same shape as
// freeappstore-online/platform scripts/fleet-deploy-workflow.mjs.
//
// Dry run by default: it clones each repo shallowly, classifies the current
// workflow, checks the lockfile is in sync (game-deploy installs frozen), and
// prints a plan. --apply commits and pushes straight to main; --wait then
// watches the run, checks the live version.json names the new commit, and
// reverts the commit only if the run failed before switching the route.
//
//   node scripts/fleet-deploy-workflow.mjs [--apply [--wait]] [--all | <repo>...]
//
// Idempotent: an up-to-date repo is skipped. Workflows carrying anything the
// generator does not reproduce are listed for hand review and never rewritten.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ORG = 'freegamestore-online';
const WORKFLOW = '.github/workflows/deploy.yml';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** The games SDK release every game moves to (#498: sign-out on older Safari). */
export const GAMES_SDK = '0.20.0';

export const COMMIT_MESSAGE = `ci: keyless OIDC deploy workflow; games SDK ${GAMES_SDK}

Calls ci-workflows game-deploy.yml pinned by commit: the build has no
secrets, and the deploy uploads through admin.freegamestore.online with a
GitHub OIDC token, so no R2 key reaches this repo's workflow. Moves
@freegamestore/games to ^${GAMES_SDK} (sign-out fix, #498) where it was older.
Generated by freegamestore-online/platform scripts/fleet-deploy-workflow.mjs.

Refs freegamestore-online/platform#488, freegamestore-online/platform#438

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`;

const REVERT_MESSAGE = (sha, url) => `revert: restore the previous deploy workflow

The keyless workflow from ${sha.slice(0, 7)} failed before deploying (${url}), so
the game still serves its previous build. Restored by
freegamestore-online/platform scripts/fleet-deploy-workflow.mjs.

Refs freegamestore-online/platform#488, freegamestore-online/platform#438

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`;

/** Steps the legacy inline workflows carried; anything else is a creator's own. */
const KNOWN_STEPS = new Set([
  'No external <script src> (games must be self-contained)',
  'No tracking SDKs in source',
  'Install',
  'Build',
  'Verify build output',
  'Stamp version.json',
  'Smoke test built game',
  'Upload to R2',
]);
const KNOWN_ACTIONS = /^(actions\/checkout|pnpm\/action-setup|actions\/setup-node)@/;
const R2_SECRETS = new Set(['R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY', 'R2_ACCOUNT_ID']);
const REUSABLE =
  /freegamestore-online\/ci-workflows\/\.github\/workflows\/(game-ci|game-deploy)\.yml@\S+/;

const uncommented = (text) => text.replace(/^\s*#.*$/gm, '');

/**
 * The deploy shape a workflow has, and why it needs hand review (empty when the
 * generator reproduces everything it does). Line-based: the inline variants are
 * regular, and the reusable callers are a few lines. Exported for the tests.
 */
export function classify(text, generated) {
  if (text == null) return { variant: 'no-deploy-yml', review: ['no deploy.yml'] };
  if (text === generated) return { variant: 'current', review: [] };
  const code = uncommented(text);
  const review = [];
  const secrets = new Set([...code.matchAll(/secrets\.(\w+)/g)].map((m) => m[1]));
  const extraSecrets = [...secrets].filter((s) => !R2_SECRETS.has(s));
  if (extraSecrets.length) review.push(`secrets ${extraSecrets.join(',')}`);
  if (/\$\{\{\s*vars\./.test(code)) review.push('repo variables');
  if (/wrangler|CLOUDFLARE_/.test(code)) review.push('wrangler/Cloudflare token');
  const reusable = REUSABLE.exec(code);
  if (reusable) {
    if (/\bwith:\s*\n\s+(?!cf_project:)\w+:/.test(code)) review.push('reusable workflow inputs');
    return {
      variant: reusable[1] === 'game-deploy' ? 'keyless-outdated' : 'game-ci-caller',
      review,
    };
  }
  for (const [, uses] of code.matchAll(/^\s*-?\s*uses:\s*(\S+)/gm))
    if (!KNOWN_ACTIONS.test(uses)) review.push(`action ${uses}`);
  for (const [, name] of code.matchAll(/^\s*- name:\s*(.+?)\s*$/gm))
    if (!KNOWN_STEPS.has(name)) review.push(`step "${name}"`);
  const triggers = [...code.matchAll(/^ {2}(\w+):/gm)]
    .map((m) => m[1])
    .filter((t) =>
      ['push', 'pull_request', 'workflow_dispatch', 'schedule', 'release'].includes(t),
    );
  if (triggers.some((t) => !['push', 'workflow_dispatch'].includes(t)))
    review.push(`triggers ${triggers.join(',')}`);
  for (const [, source] of code.matchAll(/aws s3 sync (\S+)/g))
    if (source !== './web/dist') review.push(`syncs ${source}`);
  if (!/aws s3 sync/.test(code)) review.push('no R2 sync');
  if (/^\s+run: pnpm build\s*$/m.test(code) === false) review.push('build command');
  return {
    variant: /Stamp version\.json/.test(code) ? 'inline-versionjson' : 'inline',
    review: [...new Set(review)],
  };
}

/** web/package.json with @freegamestore/games moved to ^GAMES_SDK, or null if already there. */
export function bumpGamesSdk(text) {
  const pkg = JSON.parse(text);
  for (const field of ['dependencies', 'devDependencies']) {
    const range = pkg[field]?.['@freegamestore/games'];
    if (!range) continue;
    const [major, minor] = (/(\d+)\.(\d+)/.exec(range) ?? []).slice(1).map(Number);
    const [wantMajor, wantMinor] = GAMES_SDK.split('.').map(Number);
    if (major > wantMajor || (major === wantMajor && minor >= wantMinor)) return null;
    pkg[field]['@freegamestore/games'] = `^${GAMES_SDK}`;
    return `${JSON.stringify(pkg, null, 2)}\n`;
  }
  return null;
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts });
}

function tryRun(cmd, args, opts) {
  try {
    return { ok: true, out: sh(cmd, args, opts) };
  } catch (error) {
    return { ok: false, out: `${error.stdout ?? ''}${error.stderr ?? ''}`.trim() };
  }
}

async function get(url) {
  try {
    const res = await fetch(url, { redirect: 'manual', signal: AbortSignal.timeout(15000) });
    return { status: res.status, text: await res.text() };
  } catch {
    return { status: 0, text: '' };
  }
}

/** Clone, classify and check one repo. Leaves the clone (with the edits) for --apply. */
async function inspect(repo, generated, workdir, registry) {
  const dir = join(workdir, repo);
  rmSync(dir, { recursive: true, force: true });
  sh('gh', ['repo', 'clone', `${ORG}/${repo}`, dir, '--', '--depth', '1', '--quiet']);
  const path = join(dir, WORKFLOW);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  const { variant, review } = classify(current, generated);
  const otherR2 = tryRun('git', [
    '-C',
    dir,
    'grep',
    '-l',
    'secrets\\.R2_',
    '--',
    '.github/workflows',
  ])
    .out.split('\n')
    .filter((f) => f && f !== WORKFLOW);
  if (otherR2.length) review.push(`R2 secrets also in ${otherR2.join(',')}`);
  const entry = registry.find((g) => g.id === repo);
  if (!entry) review.push('not in the registry');
  else if (entry.repo && entry.repo.toLowerCase() !== `${ORG}/${repo}`)
    review.push(`registry repo is ${entry.repo}`);

  // The SDK bump rewrites web/package.json and resolves the lockfile without
  // running any package script; the frozen install game-deploy runs must pass.
  const webPkg = join(dir, 'web/package.json');
  const bumped = existsSync(webPkg) ? bumpGamesSdk(readFileSync(webPkg, 'utf8')) : null;
  if (bumped) writeFileSync(webPkg, bumped);
  if (!existsSync(join(dir, 'pnpm-lock.yaml'))) review.push('no pnpm-lock.yaml (frozen install)');
  else if (bumped) {
    const lock = tryRun('pnpm', ['install', '--lockfile-only', '--ignore-scripts'], { cwd: dir });
    if (!lock.ok) review.push(`lockfile: ${lock.out.split('\n').at(-1)}`);
  } else {
    const lock = tryRun(
      'pnpm',
      ['install', '--frozen-lockfile', '--lockfile-only', '--ignore-scripts'],
      {
        cwd: dir,
      },
    );
    if (!lock.ok) review.push('lockfile out of date');
  }
  const live = await get(`https://${repo}.freegamestore.online/`);
  if (live.status !== 200) review.push(`site returns ${live.status}`);
  const changed = variant !== 'current' || Boolean(bumped);
  const action = !changed ? 'skip' : review.length ? 'review' : 'update';
  return {
    repo,
    dir,
    variant: bumped ? `${variant}+sdk` : variant,
    action,
    review,
    bumped: Boolean(bumped),
  };
}

async function waitForDeploy(repo, sha) {
  for (let i = 0; i < 90; i++) {
    const runs = JSON.parse(
      sh('gh', [
        'run',
        'list',
        '--repo',
        `${ORG}/${repo}`,
        '--commit',
        sha,
        '--workflow',
        'deploy.yml',
        '--json',
        'databaseId,status,conclusion,url,event',
      ]),
    ).filter((r) => r.event === 'push');
    const run = runs[0];
    if (run?.status === 'completed') {
      const { jobs } = JSON.parse(
        sh('gh', [
          'run',
          'view',
          String(run.databaseId),
          '--repo',
          `${ORG}/${repo}`,
          '--json',
          'jobs',
        ]),
      );
      const deploy = jobs.find((j) => /deploy/.test(j.name) && !/compliance|build/.test(j.name));
      return { ...run, deployJob: deploy?.conclusion || 'skipped' };
    }
    await new Promise((r) => setTimeout(r, 20000));
  }
  return { conclusion: 'timeout' };
}

async function apply(plan, generated, wait) {
  const { repo, dir } = plan;
  mkdirSync(join(dir, '.github/workflows'), { recursive: true });
  writeFileSync(join(dir, WORKFLOW), generated);
  sh('git', [
    '-C',
    dir,
    'add',
    WORKFLOW,
    ...(plan.bumped ? ['web/package.json', 'pnpm-lock.yaml'] : []),
  ]);
  sh('git', ['-C', dir, 'commit', '--quiet', '-m', COMMIT_MESSAGE]);
  if (!tryRun('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']).ok) {
    sh('git', ['-C', dir, 'pull', '--rebase', '--quiet', 'origin', 'main']);
    sh('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']);
  }
  const sha = sh('git', ['-C', dir, 'rev-parse', 'HEAD']).trim();
  console.log(`${repo}: pushed ${sha.slice(0, 7)}`);
  if (!wait) return { ...plan, sha };
  const run = await waitForDeploy(repo, sha);
  if (run.conclusion === 'success') {
    const version = await get(`https://${repo}.freegamestore.online/version.json`);
    let commit = '';
    try {
      commit = JSON.parse(version.text).commit;
    } catch {}
    return {
      ...plan,
      sha,
      run: run.url,
      result:
        commit === sha ? 'green' : `deployed; version.json commit ${commit || version.status}`,
    };
  }
  // Revert only when the deploy job never started (the build failed): then no
  // keyless release went live and the game still serves its legacy files. A
  // deploy job that failed may have switched the route already (a lost commit
  // response), and the legacy sync's --delete would then remove the release
  // the route serves, so that, and any keyless repo, is left for a person.
  if (
    plan.variant.startsWith('keyless') ||
    run.conclusion !== 'failure' ||
    run.deployJob !== 'skipped'
  )
    return {
      ...plan,
      sha,
      run: run.url,
      result: `run ${run.conclusion} (deploy job ${run.deployJob}); not reverted, check by hand`,
    };
  sh('git', ['-C', dir, 'pull', '--rebase', '--quiet', 'origin', 'main']);
  sh('git', ['-C', dir, 'revert', '--no-commit', sha]);
  sh('git', ['-C', dir, 'commit', '--quiet', '-m', REVERT_MESSAGE(sha, run.url)]);
  sh('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']);
  return { ...plan, sha, run: run.url, result: `reverted (run ${run.conclusion})` };
}

function allGameRepos() {
  return sh('gh', [
    'repo',
    'list',
    ORG,
    '--limit',
    '1000',
    '--no-archived',
    '--json',
    'name',
    '--jq',
    '.[].name',
  ])
    .split('\n')
    .filter(
      (name) =>
        name &&
        !['platform', 'ci-workflows', 'brand', 'public'].includes(name) &&
        !name.startsWith('template-') &&
        !name.startsWith('e2e-') &&
        !name.startsWith('.'),
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const applyChanges = args.includes('--apply');
  const wait = args.includes('--wait');
  const repos = args.includes('--all') ? allGameRepos() : args.filter((a) => !a.startsWith('--'));
  if (!repos.length) throw new Error('Name repos or pass --all');
  const { GAME_DEPLOY_WORKFLOW } = await import(
    pathToFileURL(join(ROOT, 'packages/compliance/dist/index.js'))
  );
  const registry = JSON.parse(
    readFileSync(join(ROOT, 'sites/freegamestore/registry.json'), 'utf8'),
  ).games;
  const workdir = join(tmpdir(), 'fgs-fleet-deploy');
  mkdirSync(workdir, { recursive: true });
  const results = [];
  for (const repo of repos) {
    let plan;
    try {
      plan = await inspect(repo, GAME_DEPLOY_WORKFLOW, workdir, registry);
    } catch (error) {
      plan = { repo, variant: 'error', action: 'review', review: [error.message.split('\n')[0]] };
    }
    if (applyChanges && plan.action === 'update')
      plan = await apply(plan, GAME_DEPLOY_WORKFLOW, wait);
    results.push(plan);
    console.log(
      [plan.repo, plan.variant, plan.action, plan.result ?? '', plan.review.join('; ')].join('\t'),
    );
  }
  const counts = {};
  for (const r of results)
    counts[`${r.variant}/${r.action}`] = (counts[`${r.variant}/${r.action}`] ?? 0) + 1;
  console.log(JSON.stringify(counts, null, 2));
  if (!applyChanges) console.log('Dry run: nothing pushed. Re-run with --apply [--wait].');
}

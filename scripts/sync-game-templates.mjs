// Template generator and drift check for the template-game-* repos (#494, #452).
//
// The ten templates seed every new game, and `fgs init` copies their
// `.github/workflows/deploy.yml`. That file must be GAME_DEPLOY_WORKFLOW from
// packages/compliance (build it first), the keyless caller of ci-workflows
// game-deploy.yml, and nothing else may deploy or auto-commit:
//
//   deploy.yml       is exactly GAME_DEPLOY_WORKFLOW
//   update-deps.yml  absent (it ran `pnpm up -r --latest` and pushed to main)
//   workflows        reference no secrets.R2_*
//
//   node scripts/sync-game-templates.mjs            # check: exit 1 on drift
//   node scripts/sync-game-templates.mjs --apply    # fix: commit and push to main
//
// The check reads the public template repos over the API, so CI needs no secret.

import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ORG = 'freegamestore-online';
const WORKFLOWS = '.github/workflows';
const DEPLOY = `${WORKFLOWS}/deploy.yml`;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The engine templates `fgs init` and the agent seed from (ENGINE_TEMPLATE_REPOS). */
export const TEMPLATES = [
  'canvas',
  'grid',
  '3d',
  'cards',
  'kaplay',
  'phaser',
  'pixi',
  'babylon',
  'excalibur',
  'littlejs',
].map((engine) => `template-game-${engine}`);

export const COMMIT_MESSAGE = `ci: deploy.yml from the platform generator; drop the update-deps cron

deploy.yml is now GAME_DEPLOY_WORKFLOW, the keyless caller of ci-workflows
game-deploy.yml: no R2 secret, a frozen-lockfile install, the fgs check gate.
update-deps.yml ran \`pnpm up -r --latest\` and pushed to main on a schedule;
it is removed. Generated by freegamestore-online/platform
scripts/sync-game-templates.mjs, which CI re-checks.

Refs freegamestore-online/platform#494, freegamestore-online/platform#452, freegamestore-online/platform#488

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`;

/**
 * What differs in one template, given its workflow files as {name: text}.
 * Empty when it matches the generator. Exported for the tests.
 */
export function drift(files, generated) {
  const problems = [];
  if (files[DEPLOY] === undefined) problems.push('deploy.yml is missing');
  else if (files[DEPLOY] !== generated)
    problems.push('deploy.yml differs from GAME_DEPLOY_WORKFLOW');
  if (files[`${WORKFLOWS}/update-deps.yml`] !== undefined)
    problems.push('update-deps.yml still exists');
  for (const [name, text] of Object.entries(files))
    if (/secrets\.R2_/.test(text.replace(/^\s*#.*$/gm, '')))
      problems.push(`${name} reads R2 secrets`);
  return problems;
}

function gh(args, opts = {}) {
  return execFileSync('gh', args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    ...opts,
  });
}

/** Every workflow file in a template's default branch, read over the API. */
function remoteWorkflows(repo) {
  const files = {};
  const list = JSON.parse(gh(['api', `repos/${ORG}/${repo}/contents/${WORKFLOWS}`]));
  for (const { path } of list) {
    const file = JSON.parse(gh(['api', `repos/${ORG}/${repo}/contents/${path}`]));
    files[path] = Buffer.from(file.content, 'base64').toString('utf8');
  }
  return files;
}

function apply(repo, generated, workdir) {
  const dir = join(workdir, repo);
  rmSync(dir, { recursive: true, force: true });
  gh(['repo', 'clone', `${ORG}/${repo}`, dir, '--', '--depth', '1', '--quiet']);
  writeFileSync(join(dir, DEPLOY), generated);
  rmSync(join(dir, WORKFLOWS, 'update-deps.yml'), { force: true });
  execFileSync('git', ['-C', dir, 'add', '-A', WORKFLOWS]);
  execFileSync('git', ['-C', dir, 'commit', '--quiet', '-m', COMMIT_MESSAGE]);
  execFileSync('git', ['-C', dir, 'push', '--quiet', 'origin', 'HEAD:main']);
  return execFileSync('git', ['-C', dir, 'rev-parse', '--short', 'HEAD'], {
    encoding: 'utf8',
  }).trim();
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const applyChanges = process.argv.includes('--apply');
  const { GAME_DEPLOY_WORKFLOW } = await import(
    pathToFileURL(join(ROOT, 'packages/compliance/dist/index.js'))
  );
  const workdir = join(tmpdir(), 'fgs-sync-game-templates');
  mkdirSync(workdir, { recursive: true });
  let drifted = 0;
  for (const repo of TEMPLATES) {
    const problems = drift(remoteWorkflows(repo), GAME_DEPLOY_WORKFLOW);
    if (!problems.length) {
      console.log(`${repo}: ok`);
      continue;
    }
    drifted++;
    if (applyChanges)
      console.log(
        `${repo}: pushed ${apply(repo, GAME_DEPLOY_WORKFLOW, workdir)} (${problems.join('; ')})`,
      );
    else console.log(`${repo}: DRIFT ${problems.join('; ')}`);
  }
  if (drifted && !applyChanges) {
    console.error(
      `${drifted} template(s) drifted. Run: node scripts/sync-game-templates.mjs --apply`,
    );
    process.exit(1);
  }
}
